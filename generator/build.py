"""Orchestrates: data -> portrait -> SVGs (dark + light) -> README block."""
from __future__ import annotations
import html
import os
import sys
import tempfile
import webbrowser

from . import config, github_data as gd, portrait, sections as S
from .kit import PALETTES

START, END = "<!-- PROFILE:START -->", "<!-- PROFILE:END -->"
GEN = "generated"


def log(msg: str) -> None:
    print(f"[profile] {msg}", flush=True)
    if msg.startswith("WARNING") and os.environ.get("GITHUB_ACTIONS"):
        print(f"::warning title=Profile data fallback::{msg}", flush=True)   # visible in the Actions UI


def acquire_data(cfg: dict, demo: bool, offline: bool) -> dict:
    if demo:
        log("DEMO mode: using sample data (never use this for the live profile)")
        return gd.demo_data(cfg["username"])
    if not offline:
        token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
        try:
            data = gd.fetch_live(cfg["username"], token)
            gd.save_cache(data)
            log(f"Fetched live data for @{cfg['username']}")
            return data
        except gd.FetchError as exc:
            log(f"WARNING live fetch failed: {exc}")
    cached = gd.load_cache()
    if cached and not cached.get("demo"):
        log(f"WARNING using cached snapshot from {cached['fetched_at']} (live data unavailable)")
        return cached
    raise SystemExit("No live data and no usable cache: refusing to overwrite outputs.")


def render_all(cfg: dict, data: dict) -> dict[str, str]:
    """Returns {filename: svg}. Nothing is written until every render succeeds."""
    rows = portrait.get_portrait(cfg, data)
    projects = gd.select_projects(data, cfg)
    files: dict[str, str] = {}
    for mode, pal in PALETTES.items():
        files[f"hero-{mode}.svg"] = S.hero(pal, rows, cfg)
        files[f"activity-{mode}.svg"] = S.activity(pal, data)
        files[f"overview-{mode}.svg"] = S.overview(pal, data)
        files[f"stack-{mode}.svg"] = S.stack(pal, cfg)
        files[f"projects-head-{mode}.svg"] = S.projects_head(pal)
        for i, repo in enumerate(projects, 1):
            files[f"project-{i}-{mode}.svg"] = S.project_row(pal, i, repo)
        files[f"snake-{mode}.svg"] = S.snake(pal, data)
        files[f"footer-{mode}.svg"] = S.footer(pal, cfg, data)
    files["spacer.svg"] = '<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"/>\n'
    return files


# ── README ───────────────────────────────────────────────────────────
def picture(name: str, alt: str, attrs: str = 'width="100%"') -> str:
    a = html.escape(alt, quote=True)
    return (f'<picture>\n'
            f'  <source media="(prefers-color-scheme: dark)" srcset="{GEN}/{name}-dark.svg">\n'
            f'  <img {attrs} alt="{a}" src="{GEN}/{name}-light.svg">\n'
            f'</picture>')


def readme_block(cfg: dict, data: dict, n_projects: int) -> str:
    links = " &nbsp;·&nbsp; ".join(
        f'<a href="{html.escape(u, quote=True)}">{html.escape(k)}&nbsp;↗</a>' for k, u in cfg["links"].items())
    projects = gd.select_projects(data, cfg)
    rows = "\n".join(
        f'<a href="{html.escape(p["url"], quote=True)}">\n{picture(f"project-{i}", p["name"])}\n</a>'
        for i, p in enumerate(projects, 1))
    return f"""{START}
<!-- Generated by generator/ — edit profile.toml, not this block. -->
<div>
{picture("hero", f"{cfg['name']}, {cfg['role']}. ASCII portrait and introduction.")}
<p align="center"><img src="{GEN}/spacer.svg" width="{S.TEXT_COL_PCT}%" height="1" alt="">{links}</p>
</div>

<br>

{picture("activity", "Contribution activity over the last 12 months")}

{picture("overview", "GitHub statistics and language breakdown")}

{picture("stack", "Tech stack and what I am currently learning")}

{picture("projects-head", "Projects")}
{rows}

<br>

{picture("snake", "Contribution snake animation")}

{picture("footer", "Footer")}
{END}"""


def update_readme(cfg: dict, data: dict, n_projects: int, path=None) -> bool:
    path = path or config.safe_path("README.md")
    block = readme_block(cfg, data, n_projects)
    if path.exists():
        cur = path.read_text(encoding="utf-8")
        if START in cur and END in cur:
            head, rest = cur.split(START, 1)
            _, tail = rest.split(END, 1)
            new = head + block + tail
        else:
            log("README.md has no PROFILE markers; leaving it untouched (see docs/SETUP.md)")
            return False
    else:
        new = block + "\n"
    if path.exists() and path.read_text(encoding="utf-8") == new:
        return False
    path.write_text(new, encoding="utf-8")
    return True


def write_atomic(path, content: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=path.parent, suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.replace(tmp, path)


def run(demo: bool = False, offline: bool = False) -> int:
    cfg = config.load()
    data = acquire_data(cfg, demo, offline)
    files = render_all(cfg, data)

    out = config.GENERATED_DIR
    out.mkdir(exist_ok=True)
    keep = set(files) | {"data.json", "portrait.txt"}
    for old in out.iterdir():                    # drop outputs of a previous, larger run
        if old.name not in keep and old.suffix == ".svg":
            old.unlink()
    for name, svg in files.items():
        write_atomic(config.safe_path(f"{GEN}/{name}"), svg)
    changed = update_readme(cfg, data, len(gd.select_projects(data, cfg)))
    log(f"Wrote {len(files)} SVG files; README {'updated' if changed else 'unchanged'}")
    return 0


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    try:
        code = run(demo="--demo" in argv, offline="--offline" in argv)
        if code == 0 and "--open" in argv:          # open the combined local preview
            webbrowser.open((config.ROOT / "preview.html").as_uri())
        return code
    except config.ConfigError as exc:
        print(f"Config error: {exc}", file=sys.stderr)
        return 2
